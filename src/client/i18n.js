let service = null
let bound = null
export function setupLocale(ctx) {
  const l = ctx.get('locale')
  if (!l) return
  service = l
  try {
    l.register(NS, 'zh', zh)
    l.register(NS, 'en', en)
  } catch {}
  bound = l.bind(NS)
}
export function t(key) {
  return bound ? bound(key) : zh[key] ?? key
}
export const subscribe = (cb) => (service && typeof service.subscribe === 'function' ? service.subscribe(cb) : () => {})
export const snapshot = () => (service && typeof service.getSnapshot === 'function' ? service.getSnapshot() : null)
